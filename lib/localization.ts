const orderedCopy = [...copy].sort((a, b) => b[0].length - a[0].length);

function replaceCopy(value: string, language: AppLanguage) {
  return orderedCopy.reduce((result, [zh, en]) => {
    const from = language === "en" ? zh : en;
    const to = language === "en" ? en : zh;
    return result.split(from).join(to);
  }, value);
}

/** Localize presentation copy without mutating saved transactions or form values. */
export function localizeRenderedApp(language: AppLanguage) {
  const root = document.querySelector<HTMLElement>(".shell");
  if (!root) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  let node = walker.nextNode();
  while (node) {
    if (!(node.parentElement?.closest("[data-localize-skip]"))) textNodes.push(node as Text);
    node = walker.nextNode();
  }
  textNodes.forEach((text) => { text.nodeValue = replaceCopy(text.nodeValue ?? "", language); });

  root.querySelectorAll<HTMLElement>("[placeholder], [aria-label], [title]").forEach((element) => {
    ["placeholder", "aria-label", "title"].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, replaceCopy(value, language));
    });
  });
}
